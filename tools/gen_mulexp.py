VECS = [
    (0x00000000, 0x00000000),
    (0x00000001, 0xFFFFFFFF),
    (0xFFFFFFFF, 0xFFFFFFFF),
    (0x80000000, 0x80000000),
    (0x0000FFFF, 0x0000FFFF),
    (0xFFFF0000, 0xFFFF0000),
    (0x12345678, 0x9ABCDEF0),
    (0xDEADBEEF, 0xCAFEBABE),
    (0x00010000, 0x00010000),
    (0x7FFFFFFF, 0x7FFFFFFF),
    (0x0001B7A5, 0x0000A3C1),
    (0xCBF43926, 0x00000003),
]
out = ["/* generated by tools/gen_mulexp.py - do not edit */",
       "#define N_MULV %d" % len(VECS)]
out.append("static const uint32_t mv_a[N_MULV] = {%s};" % ", ".join("0x%08Xu" % a for a, b in VECS))
out.append("static const uint32_t mv_b[N_MULV] = {%s};" % ", ".join("0x%08Xu" % b for a, b in VECS))
out.append("static const uint32_t mv_lo[N_MULV] = {%s};" % ", ".join("0x%08Xu" % ((a * b) & 0xFFFFFFFF) for a, b in VECS))
out.append("static const uint32_t mv_hi[N_MULV] = {%s};" % ", ".join("0x%08Xu" % ((a * b) >> 32) for a, b in VECS))
open("firmware/mulexp.h", "w").write("\n".join(out) + "\n")
print("wrote firmware/mulexp.h")
