import math
DEGS = [0, 30, 45, 60, 90, 120, 180, 225, 270, 315]
XS = [2, 10, 100, 1000, 65535, 1000000]
def q(v):
    return int(round(v * 65536.0))
out = []
out.append("/* generated by tools/gen_mathexp.py - do not edit */")
out.append("#define N_DEG %d" % len(DEGS))
out.append("static const uint32_t exp_deg[N_DEG] = {%s};" % ", ".join("%du" % d for d in DEGS))
out.append("static const int32_t exp_cos[N_DEG] = {%s};" % ", ".join(str(q(math.cos(math.radians(d)))) for d in DEGS))
out.append("static const int32_t exp_sin[N_DEG] = {%s};" % ", ".join(str(q(math.sin(math.radians(d)))) for d in DEGS))
out.append("#define N_X %d" % len(XS))
out.append("static const uint32_t exp_x[N_X] = {%s};" % ", ".join("%du" % x for x in XS))
out.append("static const int32_t exp_ln[N_X] = {%s};" % ", ".join(str(q(math.log(x))) for x in XS))
open("firmware/mathexp.h", "w").write("\n".join(out) + "\n")
print("wrote firmware/mathexp.h")
